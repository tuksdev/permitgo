class DocumentType {
  final String code; 
  final String name; 
  File? file;
  bool isUploaded; 

  DocumentType({required this.code, required this.name, this.file, this.isUploaded = false});
}

// ====================================================================
// WIDGET 1: DocumentListScreen (Shows the list of requirements)
// ====================================================================
class DocumentListScreen extends StatefulWidget {
  // Assuming Application ID is the ID generated by the backend when the application was first submitted
  final String applicationId; 
  final String businessName; 
  final String documentPurpose; // e.g., 'Registration' or 'Renewal'

  const DocumentListScreen({
    super.key, 
    required this.applicationId,
    required this.businessName,
    required this.documentPurpose,
  });

  @override
  State<DocumentListScreen> createState() => _DocumentListScreenState();
}

class _DocumentListScreenState extends State<DocumentListScreen> {
  List<DocumentType> _requiredDocuments = [];
  bool _isScreenLoading = true;
  
  // NOTE: Deleted the hardcoded _getDocumentsByPurpose method here 
  // as the requirements are now dynamically fetched from the API.

  // --- Initialization Logic ---
  @override
  void initState() {
    super.initState();
    // Start fetching the document list and their current upload status
    _fetchRequirementsAndStatus();
  }
  
  Future<void> _fetchRequirementsAndStatus() async {
    setState(() => _isScreenLoading = true);
    
    try {
      // API call to the Flask backend to get the required list based on purpose
      final response = await ApiService.fetchRequirements(widget.documentPurpose); 

      if (response['status'] == 'success') {
        List<DocumentType> documents = [];
        List<dynamic> reqs = response['requirements'] ?? []; 
        
        for (var req in reqs) {
          documents.add(DocumentType(
            code: req['req_code'], 
            // The name should include the description from the database
            name: req['description'], 
            // In a production app, you would check a separate API endpoint here
            // to set isUploaded: true if a file for this req_code exists for this applicationId.
            isUploaded: req.containsKey('is_uploaded') ? (req['is_uploaded'] == 1) : false, 
          ));
        }

        if(mounted) {
          setState(() {
            _requiredDocuments = documents;
            _isScreenLoading = false;
          });
        }
      } else {
        // Handle API failure
        if(mounted) {
          ScaffoldMessenger.of(context).showSnackBar(
            SnackBar(content: Text(response['message'] ?? 'Failed to load requirements.')),
          );
          setState(() {
            _isScreenLoading = false;
          });
        }
      }
    } catch (e) {
      if(mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(content: Text('Error contacting server: $e')),
        );
        setState(() {
          _isScreenLoading = false;
        });
      }
    }
  }

  String _getConditionalLabel(String reqCode, String documentPurpose) {
    // 1. Conditional based on Business Type/Status
    switch (reqCode) {
      case 'CONTRACT_LEASE':
      case 'LESSOR_BP':
        return 'Required if Property is Rented (Lessee)';
      case 'MAFSO_CERT':
        return 'Required for Fishing/Fish Pond Business';
      case 'PNP_CL':
      case 'OR_CR':
      case 'TA_CERT':
        return 'Required for Transport Operation';
    }

    // 2. Conditional based on Application Type (to highlight specific renewal/retirement docs)
    if (documentPurpose == 'Renewal') {
      if (reqCode == 'ITR_VAT') return 'Renewal Specific Document';
    } else if (documentPurpose == 'Retirement') {
      if (reqCode == 'ORIGINAL_PERMIT' || reqCode == 'LETTER_REQUEST' || reqCode == 'BRGY_CLOSURE' || reqCode == 'CLOSED_PIC') {
        return 'Retirement Specific Document';
      }
    }
    
    return ''; // Default for core/general requirements
  }

  // --- Utility: Check if all required documents have been uploaded ---
  bool get _isAllUploaded => _requiredDocuments.every((doc) => doc.isUploaded);
  
  void _finalizeSubmission() {
    // This marks the end of the process (Final Submit button)
    ScaffoldMessenger.of(context).showSnackBar(
      const SnackBar(content: Text('Application marked as submitted! Pending review.')),
    );
    if (!mounted) return;
    // Navigates back to the Dashboard/Home
    // Assuming DashboardScreen.routeName is correctly defined
    Navigator.popUntil(context, (route) => route.isFirst || route.settings.name == DashboardScreen.routeName); 
  }

  // --- Navigation to Picker Screen ---
  void _navigateToPicker(DocumentType doc) {
    Navigator.push(
      context,
      MaterialPageRoute(
        builder: (_) => DocumentPickerScreen(
          applicationId: widget.applicationId,
          document: doc, 
          documentPurpose: widget.documentPurpose,
        ),
      ),
    ).then((result) {
      // Logic to update the list view when returning from the picker screen
      if (result == true) {
        // Signal a successful upload was completed
        final index = _requiredDocuments.indexWhere((d) => d.code == doc.code);
        if (index != -1) {
          setState(() {
            _requiredDocuments[index].isUploaded = true;
          });
        }
      }
    });
  }

  // --- UI Build ---
  @override
  Widget build(BuildContext context) {
    if (_isScreenLoading) {
      return const Scaffold(appBar: DocumentsAppBar(title: 'Loading...'), body: Center(child: CircularProgressIndicator()));
    }
    
    return Scaffold(
      appBar: DocumentsAppBar(title: '${widget.documentPurpose} Requirements'),
      
      // Floating button visible only when all documents are uploaded
      floatingActionButton: _isAllUploaded ? FloatingActionButton.extended(
        onPressed: _finalizeSubmission,
        label: const Text('Finalize Submission', style: TextStyle(fontSize: 16)),
        icon: const Icon(Icons.send),
        backgroundColor: Colors.green,
      ) : null,
      floatingActionButtonLocation: FloatingActionButtonLocation.centerFloat,

      body: Column(
        children: [
          Padding(
            padding: const EdgeInsets.all(16.0),
            child: Text(
              'Upload requirements for ${widget.documentPurpose} ID: ${widget.applicationId}',
              style: TextStyle(fontSize: 16, fontWeight: FontWeight.w500, color: _isAllUploaded ? Colors.green : Colors.black),
              textAlign: TextAlign.center,
            ),
          ),
          
          Expanded(
            child: ListView.builder(
              padding: const EdgeInsets.symmetric(horizontal: 16.0),
              itemCount: _requiredDocuments.length,
              itemBuilder: (context, index) {
                final doc = _requiredDocuments[index];
                
                final conditionalLabel = _getConditionalLabel(doc.code, widget.documentPurpose);
                
                // Determine the status text (UPLOADED or Tap to upload)
                String statusText = doc.isUploaded ? 'Status: UPLOADED.' : 'Tap here to upload';
                
                // Construct the final subtitle: Conditional Label (if exists) + Status Text
                String subtitleText = conditionalLabel.isEmpty 
                    ? statusText 
                    : 'Condition: $conditionalLabel\n$statusText'; // Prepend with a label
                    
                return Card(
                  margin: const EdgeInsets.symmetric(vertical: 6),
                  elevation: 1,
                  child: ListTile(
                    leading: Icon(
                      doc.isUploaded ? Icons.check_circle : Icons.upload_file,
                      color: doc.isUploaded ? Colors.green : Colors.orange,
                    ),
                    title: Text(doc.name, style: TextStyle(fontWeight: doc.isUploaded ? FontWeight.bold : FontWeight.w500)),
                    subtitle: Text(doc.isUploaded ? 'Status: UPLOADED.' : 'Tap here to upload',
                      style: TextStyle(color: doc.isUploaded ? Colors.green.shade700 : Colors.grey),
                    ),
                    trailing: const Icon(Icons.arrow_forward_ios), 
                    onTap: () => _navigateToPicker(doc), 
                  ),
                );
              },
            ),
          ),
          
          // Exit button (kept outside of the FAB for accessibility)
          Padding(
            padding: const EdgeInsets.only(left: 16, right: 16, bottom: 16, top: 8), 
            child: TextButton(
              onPressed: () {
                Navigator.popUntil(context, (route) => route.isFirst || route.settings.name == DashboardScreen.routeName);
              },
              child: const Text(
                'Exit to Dashboard (Save Progress)',
                style: TextStyle(color: Colors.red, decoration: TextDecoration.underline)
              ),
            ),
          ),
        ], // End of main Column children
      ), // End of Column
    );
  }
}


