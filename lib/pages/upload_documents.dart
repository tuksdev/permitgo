// WIDGET 2: DocumentPickerScreen (Handles single file selection/upload)
// ====================================================

class DocumentPickerScreen extends StatefulWidget {
  final String applicationId; 
  final DocumentType document;
  final String documentPurpose; 

  const DocumentPickerScreen({
    super.key, 
    required this.applicationId, 
    required this.document,
    required this.documentPurpose,
  });

  @override
  State<DocumentPickerScreen> createState() => _DocumentPickerScreenState();
}

class _DocumentPickerScreenState extends State<DocumentPickerScreen> {
  File? _selectedFile;
  bool _isUploading = false;

  // --- File Picker Logic ---
  Future<void> _pickFile() async {
    FilePickerResult? result = await FilePicker.platform.pickFiles(
      type: FileType.custom,
      allowedExtensions: const ['pdf', 'jpg', 'jpeg', 'png'],
    );

    if (result != null && result.files.single.path != null) {
      if (!mounted) return;
      setState(() {
        _selectedFile = File(result.files.single.path!);
      });
    }
  }

  // --- Upload Logic ---
  Future<void> _uploadDocument() async {
    if (_selectedFile == null) {
      ScaffoldMessenger.of(context).showSnackBar(const SnackBar(content: Text('Please select a file first.')));
      return;
    }
    if (!mounted) return;
    
    setState(() => _isUploading = true);

    try {
      final response = await ApiService.uploadDocument(
        applicationId: widget.applicationId, 
        documentName: widget.document.code, 
        file: _selectedFile!,
        documentPurpose: widget.documentPurpose,
      );

      if (!mounted) return; 

      if (response['status'] == 'success') {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(content: Text('${widget.document.name} uploaded successfully!')),
        );
        // Signal success (true) to the parent list screen
        Navigator.pop(context, true); 
      } else {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(content: Text(response['message'] ?? 'Upload failed.')),
        );
      }
    } catch (e) {
        ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text('Upload Error: ${e.toString()}')));
    } finally {
      if (!mounted) return;
      setState(() => _isUploading = false);
    }
  }

  // --- UI Build ---
  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(title: Text(widget.document.name)),
      body: Padding(
        padding: const EdgeInsets.all(24),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.stretch,
          children: [
            const Text('Requirement:', style: TextStyle(fontSize: 16)),
            Text(widget.document.name, style: const TextStyle(fontSize: 22, fontWeight: FontWeight.bold)),
            const SizedBox(height: 40),

            // File Selection Button
            ElevatedButton.icon(
              onPressed: _isUploading ? null : _pickFile,
              icon: const Icon(Icons.folder_open),
              label: const Text('Select File'),
              style: ElevatedButton.styleFrom(padding: const EdgeInsets.symmetric(vertical: 15)),
            ),
            const SizedBox(height: 20),

            // Display Selected File Status
            Container(
              padding: const EdgeInsets.all(12),
              decoration: BoxDecoration(border: Border.all(color: Colors.grey.shade300), borderRadius: BorderRadius.circular(8)),
              child: Text(_selectedFile == null ? 'No file selected.' : 'File Ready: ${_selectedFile!.path.split('/').last}'),
            ),
            const SizedBox(height: 40),

            // Upload Button
            ElevatedButton(
              onPressed: (_selectedFile != null && !_isUploading) ? _uploadDocument : null,
              style: ElevatedButton.styleFrom(backgroundColor: Colors.blue, foregroundColor: Colors.white, padding: const EdgeInsets.symmetric(vertical: 18)),
              child: _isUploading ? const CircularProgressIndicator(color: Colors.white) : const Text('Upload & Save', style: TextStyle(fontSize: 18)),
            ),
          ],
        ),
      ),
    );
  }
}

